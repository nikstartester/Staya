package com.xando.navigation_api

import kotlinx.coroutines.flow.Flow

/**
 * Передача результата с одного экрана на другой без общего ViewModel и без знания друг о друге - аналог
 * `setFragmentResult`/`FragmentResultListener` для Navigation 3.
 *
 * Как пользоваться: вызывающий экран сам генерирует `requestKey` (например, `UUID`), передаёт его в
 * [NavKey][androidx.navigation3.runtime.NavKey] вызываемого экрана и подписывается на [results] по этому
 * ключу. Вызываемый экран ничего не знает о вызывающем - только вызывает [setResult] с тем же ключом и
 * сразу же, в том же обработчике, возвращается назад.
 *
 * Контракт:
 * - Результат лежит в памяти, пока его не заберут через [results]. Подписка может появиться позже
 *   публикации: так бывает, когда процесс пересоздали, пока пользователь был на вызываемом экране, и
 *   ViewModel вызывающего ещё не создана. Буфер живёт в памяти процесса: смену конфигурации переживает,
 *   смерть процесса между публикацией и забором - нет.
 * - Под ключом хранится последнее значение: повторная публикация до забора заменяет предыдущую. Это
 *   передача состояния («выбранная порода»), а не очереди событий.
 * - Забранный результат удаляется. На один ключ ожидается один подписчик: второй результата не получит.
 * - `requestKey` либо уникальный на запрос (`UUID`), либо константа. `UUID` должен пережить смерть
 *   процесса вместе с ключом навигации вызываемого экрана, то есть лежать в `SavedStateHandle`, а не в
 *   поле ViewModel, иначе после восстановления результат опубликуют под ключом, который никто не слушает.
 *   Константа хранения не требует, но допустима, только если в back stack не может быть двух экземпляров
 *   вызывающего экрана одновременно: их ViewModel живут и слушают параллельно, и результат достанется
 *   произвольному из них. Константа должна быть уникальна на всё приложение, например с префиксом модуля.
 * - Тип результата не проверяется: вызывающий экран сам генерирует ключ и сам знает, какой тип под ним
 *   ожидает.
 *
 * Стор рассчитан на схему «выбрал, опубликовал, закрылся». Экрану, который публикует результат и остаётся
 * открытым, стор не подходит. Такой экран делит состояние с вызывающим, и этому состоянию место в общем
 * держателе, который наблюдают оба экрана.
 */
// TODO: В Navigation 3 1.2.0 появились стандартные механизмы передачи результата между
//  экранами (`ResultEventBus`, `ResultEffect`), но 1.2.0 ещё не выпущена стабильно.
//  Возможно, переедем на стандартное API передачи результата.
//  См. https://developer.android.com/guide/navigation/navigation-3/return-results
interface NavigationResultStore {

    /**
     * Публикует [result] под ключом [requestKey]. Значение хранится, пока его не заберут через [results]
     * с тем же ключом; повторная публикация до забора заменяет предыдущую.
     */
    fun <T : Any> setResult(requestKey: String, result: T)

    /**
     * Подписывается на результаты, опубликованные под ключом [requestKey]. Уже опубликованный и ещё не
     * забранный результат приходит сразу при подписке; каждый забранный результат удаляется.
     */
    fun <T : Any> results(requestKey: String): Flow<T>
}
