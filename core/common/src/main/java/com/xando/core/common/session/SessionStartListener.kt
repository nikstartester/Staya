package com.xando.core.common.session

/**
 * Участник начала сессии пользователя: сбрасывает свои данные, оставшиеся от прошлой сессии.
 *
 * Реализации регистрируются в Hilt через `@IntoSet`.
 */
interface SessionStartListener {

    /**
     * Вызывается перед началом новой сессии, до сохранения токенов. Убирает всё, что осталось от
     * прошлой сессии, как бы она ни завершилась. Ошибка прерывает вход.
     */
    suspend fun onSessionStart()
}
