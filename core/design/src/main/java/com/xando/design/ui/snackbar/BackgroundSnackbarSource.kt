package com.xando.design.ui.snackbar

import kotlinx.coroutines.flow.Flow

/**
 * Источник снекбаров о фоновых операциях, у которых нет своего экрана.
 *
 * Такая операция переживает экран, с которого её запустили, поэтому её результат показывает корень
 * приложения - единственный, кто есть на месте в любой момент. Сам корень о существе операций не
 * знает: каждый модуль переводит свои операции в готовые [StayaSnackbarData] сам.
 *
 * Реализации регистрируются через `@IntoSet` и собираются в корне приложения.
 *
 * **Только для операций, которым некому отчитаться.** Подходит ли операция, проверяется одним
 * вопросом: показал бы экран, её начавший, сообщение сам, будь он жив? Если да - это не фоновый
 * источник, и сообщение принадлежит экрану, а показывать его нужно через
 * [LocalSnackbarController]. Ошибка отправки формы, неудачное обновление списка, вообще всё, за чем
 * пользователь в этот момент наблюдает, сюда не относится - в отличие от загрузки, продолжающейся
 * после ухода с экрана, или работы, которую завёл не пользователь.
 */
interface BackgroundSnackbarSource {

    /**@SelfDocumented*/
    val snackbars: Flow<StayaSnackbarData>
}
